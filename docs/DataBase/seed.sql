-- 1. 给 dict_city 增加 province 列
-- ============================================================
ALTER TABLE `dict_city`
    ADD COLUMN `province` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '省份/直辖市' AFTER `name`,
    ADD KEY `idx_dict_city_province` (`province`);

-- 同时给 job 表加冗余 province 字段（HR 选城市时同步写入，便于按省份聚合筛选）
ALTER TABLE `job`
    ADD COLUMN `province` VARCHAR(64) NOT NULL DEFAULT '' COMMENT '省份/直辖市（冗余）' AFTER `city_id`,
    ADD KEY `idx_job_province` (`province`);

